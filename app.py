# --- Supabase Connection ---
@st.cache_resource
def init_supabase():
    try:
        url = st.secrets["supabase"]["url"]
        key = st.secrets["supabase"]["key"]
        return create_client(url, key)
    except Exception as e:
        st.error(f"Supabase 연결 설정 오류: {e}")
        st.stop()

supabase: Client = init_supabase()

